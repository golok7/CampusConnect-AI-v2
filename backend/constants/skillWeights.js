// ── Build flat lookup map ──────────────────────────────────────────────────────
// Merge all domain sections into one flat map for O(1) lookup.

const SKILL_WEIGHTS = (() => {
  const flat = {};
  for (const domain of Object.values(SKILL_WEIGHTS_BY_DOMAIN)) {
    for (const [skill, weight] of Object.entries(domain)) {
      // Later domains do not overwrite earlier ones for shared skills (e.g. grpc appears in backend + distributed_systems)
      if (!(skill in flat)) flat[skill] = weight;
    }
  }
  return flat;
})();

// ── Public API ─────────────────────────────────────────────────────────────────

/**
 * Return the recruiter-discriminative weight for a skill token.
 *
 * Lookup order:
 *   1. Resolve alias → canonical token
 *   2. Direct flat map hit
 *   3. DEFAULT_SKILL_WEIGHT for unknown skills
 *
 * Always call with a lowercased, trimmed token.
 *
 * @param  {string} skill  — lowercased, trimmed skill token
 * @returns {number}       — weight in [1.0, 5.0]
 */
function getSkillWeight(skill) {
  const canonical = SKILL_ALIASES[skill] || skill;
  return SKILL_WEIGHTS[canonical] ?? DEFAULT_SKILL_WEIGHT;
}

/**
 * Build a { skill → weight } map for a list of requested skill tokens.
 * Use this to feed into weighted skill scoring in searchService.
 *
 * @param  {string[]} skills — lowercased, trimmed skill tokens
 * @returns {{ [skill: string]: number }}
 */
function buildSkillWeightMap(skills) {
  const map = {};
  for (const skill of skills) map[skill] = getSkillWeight(skill);
  return map;
}

