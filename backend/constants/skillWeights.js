// ── Weighted Skill Ontology ────────────────────────────────────────────────────
//
// PURPOSE
//   Refine recruiter ranking by giving discriminative value to specialised skills
//   without changing the global formula weights (0.55 domain / 0.30 skill / 0.15 activity).
//   Internally replaces:
//     matchedSkills.length / requestedSkills.length
//   with:
//     Σ weight(matchedSkill) / Σ weight(requestedSkill)
//
// WEIGHT SCALE
//   1.0  — generic / ubiquitous  (Git, Docker, Python, JavaScript, HTML)
//   1.5  — common but typed      (TypeScript, React, Node.js, REST)
//   2.0  — stack-defining        (Next.js, FastAPI, Express, Vue)
//   3.0  — specialised framework (Spring Boot, Redis, PostgreSQL, NestJS)
//   4.0  — high-value infra/tool (Kafka, LangChain, gRPC, Terraform, Kubeflow)
//   5.0  — research / runtime    (LoRA, RAG, eBPF, RAFT, CRDT, ZK-Proofs, TensorRT)
//
// PHILOSOPHY
//   • Weights reflect RECRUITER DISCRIMINATIVE VALUE, not popularity.
//   • React must not outweigh Kafka. Docker must not outweigh Spring Boot.
//   • Generic glue skills (Git, Linux, Bash) stay at 1.0.
//   • Weights should be conservative — when in doubt, go lower.
//
// FUTURE EVOLUTION (do NOT implement prematurely)
//   1. Dynamic TF-IDF weights: weight = log(totalUsers / usersWithSkill)
//      → makes rare skills automatically more valuable as the corpus grows.
//   2. Stack-specific weight packs: a "Java backend" pack upweights Hibernate, JPA,
//      Spring Security differently from a "Python backend" pack.
//   3. Repo co-occurrence modifier: if skill A almost always appears with skill B,
//      their individual discriminative value decreases (they're a bundle, not a signal).
//   4. Recruiter click-through feedback: clicked candidates' skills get positive weight
//      reinforcement over time.
// ─────────────────────────────────────────────────────────────────────────────

